#!/usr/bin/env node
// Fetch authoritative SHA-256 checksums for the whisper.cpp model catalog and
// write packages/core/src/voice/whisper/checksums.ts (RFC 009 §9/§21).
//
// The model `.bin` files are Git-LFS objects on Hugging Face, whose LFS oid IS
// the SHA-256 of the file content — so we read them from the HF tree API rather
// than downloading gigabytes or hand-typing hashes. Run after bumping the
// catalog or the pinned whisper.cpp tag:
//
//   node apps/x/scripts/whisper-fetch-checksums.mjs
//
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HF_REPO = "ggerganov/whisper.cpp";
const VAD_HF_REPO = "ggml-org/whisper-vad";
const HF_REVISION = "main";

// Catalog ids whose checksums we pin. Filename is uniformly `ggml-<id>.bin`.
const MODEL_IDS = [
  "tiny.en-q5_1",
  "base.en-q5_1",
  "base-q5_1",
  "small.en-q5_1",
  "small-q5_1",
  "large-v3-turbo-q5_0",
  "large-v3-q5_0",
];
const VAD_MODEL_IDS = ["silero-v5.1.2"];
const COREML_MODEL_IDS = [
  "tiny.en",
  "base.en",
  "base",
  "small.en",
  "small",
  "large-v3-turbo",
  "large-v3",
];

const fileFor = (id) => `ggml-${id}.bin`;
const coremlFileFor = (id) => `ggml-${id}-encoder.mlmodelc.zip`;

async function fetchTree(repo) {
  const url = `https://huggingface.co/api/models/${repo}/tree/${HF_REVISION}?recursive=true&expand=true`;
  const res = await fetch(url, { headers: { "User-Agent": "rowboat-whisper-checksums" } });
  if (!res.ok) throw new Error(`HF tree fetch failed for ${repo}: ${res.status} ${res.statusText}`);
  return res.json();
}

function indexBySha(tree) {
  const byFile = new Map();
  for (const entry of tree) {
    // LFS files carry { lfs: { oid, size } }; oid is the sha256 of the content.
    const sha = entry?.lfs?.oid;
    if (entry?.path && sha) byFile.set(entry.path, sha);
  }
  return byFile;
}

async function main() {
  const modelTree = await fetchTree(HF_REPO);
  const modelFiles = indexBySha(modelTree);
  const vadFiles = indexBySha(await fetchTree(VAD_HF_REPO));
  const coremlFiles = indexBySha(modelTree);
  const coremlSizes = new Map(
    modelTree
      .filter((entry) => entry?.path && entry?.lfs?.size)
      .map((entry) => [entry.path, entry.lfs.size]),
  );

  const lines = [];
  const coremlLines = [];
  const coremlSizeLines = [];
  const missing = [];
  for (const [repo, ids, byFile] of [
    [HF_REPO, MODEL_IDS, modelFiles],
    [VAD_HF_REPO, VAD_MODEL_IDS, vadFiles],
  ]) {
    for (const id of ids) {
      const sha = byFile.get(fileFor(id));
      if (sha) lines.push(`  "${id}": "${sha}",`);
      else missing.push(`${repo}:${id}`);
    }
  }
  for (const id of COREML_MODEL_IDS) {
    const file = coremlFileFor(id);
    const sha = coremlFiles.get(file);
    const size = coremlSizes.get(file);
    if (sha) coremlLines.push(`  "${id}": "${sha}",`);
    else missing.push(`${HF_REPO}:${id}-coreml`);
    if (size) coremlSizeLines.push(`  "${id}": ${Math.ceil(size / 1024 / 1024)},`);
  }
  if (missing.length) {
    console.warn(`[checksums] no LFS oid found for: ${missing.join(", ")} (skipped)`);
  }

  const header = `/**
 * Pinned SHA-256 checksums for the whisper.cpp model catalog (RFC 009 §9/§21).
 *
 * GENERATED by apps/x/scripts/whisper-fetch-checksums.mjs — do not hand-edit.
 * Sources:
 * - Hugging Face ${HF_REPO}@${HF_REVISION} Git-LFS object ids (= file sha256).
 * - Hugging Face ${VAD_HF_REPO}@${HF_REVISION} Git-LFS object ids (= file sha256).
 * - Core ML sidecar zip archives in ${HF_REPO}@${HF_REVISION}.
 * A model with no entry here is refused at download time (unverified downloads
 * can never be installed).
 */
export const CHECKSUMS: Record<string, string> = {
${lines.join("\n")}
};

export const COREML_CHECKSUMS: Record<string, string> = {
${coremlLines.join("\n")}
};

export const COREML_SIZES_MB: Record<string, number> = {
${coremlSizeLines.join("\n")}
};
`;

  const here = dirname(fileURLToPath(import.meta.url));
  const dest = join(here, "..", "packages", "core", "src", "voice", "whisper", "checksums.ts");
  await writeFile(dest, header);
  console.log(
    `wrote ${lines.length} model checksums and ${coremlLines.length} Core ML checksums → ${dest}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
