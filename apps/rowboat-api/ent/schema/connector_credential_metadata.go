package schema

import (
	"context"

	"entgo.io/ent"
)

// refreshCredentialMetadataMutation is implemented by connection mutations
// that carry a sealed refresh token and its safe presence flag.
type refreshCredentialMetadataMutation interface {
	ent.Mutation
	RefreshTokenEncrypted() ([]byte, bool)
	SetRefreshTokenPresent(bool)
}

type refreshCredentialClearMutation interface {
	RefreshTokenEncryptedCleared() bool
	SetRefreshTokenPresent(bool)
}

// apiKeyCredentialMetadataMutation is implemented by MCP connection mutations.
type apiKeyCredentialMetadataMutation interface {
	ent.Mutation
	APIKeyEncrypted() ([]byte, bool)
	APIKeyEncryptedCleared() bool
	SetAPIKeyPresent(bool)
}

// credentialGenerationMutation lets the hook normalize additive generation
// changes into an absolute value. The history generator only observes Set
// values, so this keeps each history row aligned with the post-mutation grant.
type credentialGenerationMutation interface {
	ent.Mutation
	CredentialGeneration() (int64, bool)
	SetCredentialGeneration(int64)
	AddCredentialGeneration(int64)
	AddedCredentialGeneration() (int64, bool)
	ResetCredentialGeneration()
	OldCredentialGeneration(context.Context) (int64, error)
}

// connectorHistoryMutation is generated by enthistory for the two connection
// mutations. Connector history triggers are disabled in the history schemas so
// this hook can derive safe metadata before writing an immutable row.
type connectorHistoryMutation interface {
	ent.Mutation
	CreateHistoryFromCreate(context.Context) error
	CreateHistoryFromUpdate(context.Context) error
	CreateHistoryFromDelete(context.Context) error
}

// connectorCredentialMetadataHook derives non-secret history metadata before
// the enthistory hooks run. OAuth refresh-token replacements advance generation
// automatically. MCP callers already advance generation as part of their
// lifecycle fence, and this hook normalizes those additive changes for history.
func connectorCredentialMetadataHook(incrementRefreshGeneration bool) ent.Hook {
	return func(next ent.Mutator) ent.Mutator {
		return ent.MutateFunc(func(ctx context.Context, mutation ent.Mutation) (ent.Value, error) {
			refreshTouched := false
			if m, ok := mutation.(refreshCredentialMetadataMutation); ok {
				if ciphertext, exists := m.RefreshTokenEncrypted(); exists {
					m.SetRefreshTokenPresent(len(ciphertext) > 0)
					refreshTouched = true
				}
			}
			if m, ok := mutation.(refreshCredentialClearMutation); ok {
				if m.RefreshTokenEncryptedCleared() {
					m.SetRefreshTokenPresent(false)
					refreshTouched = true
				}
			}

			if m, ok := mutation.(apiKeyCredentialMetadataMutation); ok {
				if ciphertext, exists := m.APIKeyEncrypted(); exists {
					m.SetAPIKeyPresent(len(ciphertext) > 0)
				}
				if m.APIKeyEncryptedCleared() {
					m.SetAPIKeyPresent(false)
				}
			}

			if mutation.Op().Is(ent.OpUpdate | ent.OpUpdateOne) {
				if m, ok := mutation.(credentialGenerationMutation); ok {
					if incrementRefreshGeneration && refreshTouched {
						if _, set := m.CredentialGeneration(); !set {
							if _, added := m.AddedCredentialGeneration(); !added {
								m.AddCredentialGeneration(1)
							}
						}
					}
					if added, exists := m.AddedCredentialGeneration(); exists {
						old, err := m.OldCredentialGeneration(ctx)
						if err != nil {
							return nil, err
						}
						m.ResetCredentialGeneration()
						m.SetCredentialGeneration(old + added)
					}
				}
			}

			history, ok := mutation.(connectorHistoryMutation)
			if !ok {
				return next.Mutate(ctx, mutation)
			}
			switch {
			case mutation.Op().Is(ent.OpCreate):
				value, err := next.Mutate(ctx, mutation)
				if err != nil {
					return nil, err
				}
				if err := history.CreateHistoryFromCreate(ctx); err != nil {
					return nil, err
				}
				return value, nil
			case mutation.Op().Is(ent.OpUpdate | ent.OpUpdateOne):
				if err := history.CreateHistoryFromUpdate(ctx); err != nil {
					return nil, err
				}
				return next.Mutate(ctx, mutation)
			case mutation.Op().Is(ent.OpDelete | ent.OpDeleteOne):
				if err := history.CreateHistoryFromDelete(ctx); err != nil {
					return nil, err
				}
				return next.Mutate(ctx, mutation)
			default:
				return next.Mutate(ctx, mutation)
			}
		})
	}
}
